import random
from pathlib import Path

import numpy as np

SEED = 7
NUM_CASES = 60
OUTPUT = Path(__file__).resolve().parents[1] / "tests" / "generated" / "view_cases.inc"


def random_shape():
    ndim = random.randint(1, 4)
    return tuple(random.choice([1, 2, 3, 4]) for _ in range(ndim))


def transpose(a):
    if a.ndim == 0:
        return None
    d0, d1 = random.randrange(a.ndim), random.randrange(a.ndim)
    return np.swapaxes(a, d0, d1), ("Transpose", [d0, d1])


def permute(a):
    if a.ndim == 0:
        return None
    dims = list(range(a.ndim))
    random.shuffle(dims)
    return np.transpose(a, dims), ("Permute", dims)


def slice_dim(a):
    if a.ndim == 0:
        return None
    dim = random.randrange(a.ndim)
    size = a.shape[dim]
    start = random.randint(-size - 1, size + 1)
    end = random.randint(-size - 1, size + 1)
    step = random.randint(1, 3)
    key = [slice(None)] * a.ndim
    key[dim] = slice(start, end, step)
    return a[tuple(key)], ("Slice", [dim, start, end, step])


def select(a):
    candidates = [d for d in range(a.ndim) if a.shape[d] > 0]
    if not candidates:
        return None
    dim = random.choice(candidates)
    index = random.randint(-a.shape[dim], a.shape[dim] - 1)
    return np.take(a, index, axis=dim), ("Select", [dim, index])


def unsqueeze(a):
    dim = random.randint(0, a.ndim)
    return np.expand_dims(a, dim), ("Unsqueeze", [dim])


def squeeze(a):
    candidates = [d for d in range(a.ndim) if a.shape[d] == 1]
    if not candidates:
        return None
    dim = random.choice(candidates)
    return np.squeeze(a, axis=dim), ("Squeeze", [dim])


def expand(a):
    target = [random.randint(1, 3)] * random.randint(0, 1)
    for size in a.shape:
        target.append(random.randint(1, 3) if size == 1 else size)
    return np.broadcast_to(a, target), ("Expand", target)


def reshape(a):
    return a.reshape(-1), ("Reshape", [-1])


OPERATIONS = [transpose, permute, slice_dim, select, unsqueeze, squeeze, expand, reshape]


def cpp_list(values):
    return "{" + ", ".join(str(int(v)) for v in values) + "}"


def generate_case():
    shape = random_shape()
    array = np.arange(int(np.prod(shape))).reshape(shape)
    steps = []
    chain_length = random.randint(1, 4)
    while len(steps) < chain_length:
        result = random.choice(OPERATIONS)(array)
        if result is not None:
            array, step = result
            steps.append(step)
    ops = ", ".join(f"{{ViewOp::{name}, {cpp_list(args)}}}" for name, args in steps)
    return f"    {{{cpp_list(shape)}, {{{ops}}}, {cpp_list(array.shape)}, {cpp_list(array.ravel())}}},"


def main():
    random.seed(SEED)
    lines = ["// Generated by scripts/gen_view_cases.py. Do not edit."]
    lines += [generate_case() for _ in range(NUM_CASES)]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {NUM_CASES} cases in {OUTPUT}")


if __name__ == "__main__":
    main()
