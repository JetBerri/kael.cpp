import sys
import unicodedata
from pathlib import Path


def ranges_of(category_prefix):
    ranges = []
    for code_point in range(sys.maxunicode + 1):
        if not unicodedata.category(chr(code_point)).startswith(category_prefix):
            continue
        if ranges and ranges[-1][1] == code_point - 1:
            ranges[-1][1] = code_point
        else:
            ranges.append([code_point, code_point])
    return ranges


def table(name, ranges):
    rows = "\n".join(f"    {{0x{first:X}, 0x{last:X}}}," for first, last in ranges)
    return f"inline constexpr CodePointRange {name}[] = {{\n{rows}\n}};\n"


def main():
    output = Path(__file__).resolve().parent.parent / "src/text/unicode_classes.inc"
    output.write_text(
        f"// Generated by scripts/gen_unicode_classes.py from Unicode {unicodedata.unidata_version}.\n"
        + table("kLetters", ranges_of("L"))
        + table("kNumbers", ranges_of("N"))
    )


if __name__ == "__main__":
    main()
