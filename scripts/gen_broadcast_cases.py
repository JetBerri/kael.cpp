# Generate deterministic NumPy broadcasting fixtures for C++ tests.

import random
import numpy as np

from pathlib import Path


SEED = 42
NUM_CASES = 300
OUTPUT = Path(__file__).resolve().parents[1] / "tests" / "generated" / "broadcast_cases.inc"

def random_shape():
    ndim = random.randint(0, 4)
    return tuple(random.choices([0, 1, 2, 3], weights=[2, 3, 2, 3], k=ndim))


def cpp_shape(shape):
    return "{" + ", ".join(map(str, shape)) + "}"


def main():
    
    random.seed(SEED)
    
    lines = ["// Generated by scripts/gen_broadcast_cases.py — do not edit."]
    valid_count = 0
    invalid_count = 0

    for _ in range(NUM_CASES):
        a = random_shape()
        b = random_shape()
        try:
            expected = np.broadcast_shapes(a, b)
            valid = True
            valid_count += 1
        except ValueError:
            expected = ()
            valid = False
            invalid_count += 1

        lines.append(
            f"    {{{cpp_shape(a)}, {cpp_shape(b)}, "
            f"{'true' if valid else 'false'}, {cpp_shape(expected)}}},"
        )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    
    print(f"Generated {NUM_CASES} cases: {valid_count} valid, {invalid_count} invalid")
    print(f"Saved to: {OUTPUT}")


if __name__ == "__main__":
    main()
